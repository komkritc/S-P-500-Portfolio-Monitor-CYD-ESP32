#!/usr/bin/env python3
"""Regenerate src/network/certs_builtin.h — the built-in root CA bundle.

Trust model: the bundle holds only ROOT CA certificates. Intermediates are served by
Yahoo at handshake time; roots are stable for a decade. Roots come from the curl CA
bundle (curl.se/ca/cacert.pem), never pasted by hand.

Verified before writing anything:
  1. every selected root parses with openssl and is self-signed (a real root);
  2. the LIVE chains of the Yahoo hosts build a path to a bundled root
     (python ssl against the extracted bundle) — firmware would accept today's Yahoo.

Usage:  python3 tools/fetch_roots.py [--no-net]
  --no-net  skip the live Yahoo checks (offline regeneration from tools/cacert.pem).
Update procedure lives in docs/CERTS.md.
"""
import os, re, socket, ssl, subprocess, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "network", "certs_builtin.h")
CACERT_LOCAL = os.path.join(ROOT, "tools", "cacert.pem")
CACERT_URL = "https://curl.se/ca/cacert.pem"
HOSTS = ["query1.finance.yahoo.com", "query2.finance.yahoo.com"]

WANTED = [
    ("DigiCert Global Root G2",     "anchors today's Yahoo chain (DigiCert G2 intermediate)"),
    ("DigiCert TLS RSA4096 Root G5", "DigiCert's current generation root, already used by other Yahoo services"),
    ("ISRG Root X1",                "insurance: Let's Encrypt, if Yahoo ever moves CA"),
]

def pem_blocks(text):
    return re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", text, re.S)

def subject_cn(pem):
    p = subprocess.run(["openssl", "x509", "-noout", "-subject"], input=pem.encode(),
                       capture_output=True, check=True).stdout.decode()
    m = re.search(r"CN\s*=\s*([^,/]+)", p)
    return m.group(1).strip() if m else ""

def is_self_signed(pem):
    txt = subprocess.run(["openssl", "x509", "-noout", "-text"], input=pem.encode(),
                         capture_output=True, check=True).stdout.decode()
    s = re.search(r"Subject: (.*)", txt); i = re.search(r"Issuer: (.*)", txt)
    return bool(s and i and s.group(1).strip() == i.group(1).strip())

def enddate(pem):
    return subprocess.run(["openssl", "x509", "-noout", "-enddate"], input=pem.encode(),
                          capture_output=True, check=True).stdout.decode().strip()

def chain_ok(host, ca_path):
    ctx = ssl.create_default_context(cafile=ca_path)
    try:
        with socket.create_connection((host, 443), timeout=15) as raw:
            with ctx.wrap_socket(raw, server_hostname=host) as tls:
                return tls.getpeercert() is not None
    except Exception as e:
        print("  live chain check FAILED for %s: %s" % (host, e))
        return False

def main():
    no_net = "--no-net" in sys.argv
    text = None
    if not no_net:
        try:
            text = fetch = urllib.request.urlopen(CACERT_URL, timeout=20).read().decode()
        except Exception as e:
            print("could not download %s (%s); trying local copy" % (CACERT_URL, e))
    if text is None:
        if not os.path.exists(CACERT_LOCAL):
            sys.exit("no CA source: download %s to tools/cacert.pem or run with network" % CACERT_URL)
        text = open(CACERT_LOCAL, encoding="utf-8").read()

    by_cn = {}
    for pem in pem_blocks(text):
        cn = subject_cn(pem)
        if cn and cn not in by_cn:
            by_cn[cn] = pem

    chosen = []
    for cn, why in WANTED:
        pem = by_cn.get(cn)
        if not pem:
            sys.exit("root %r not found in the CA bundle" % cn)
        if not is_self_signed(pem):
            sys.exit("%r is not self-signed - refusing" % cn)
        print("root %-25s %s  (%s)" % (cn, enddate(pem), why))
        chosen.append((cn, pem, why))

    # sanity: the extracted bundle must verify the live Yahoo chains
    import tempfile
    with tempfile.NamedTemporaryFile("w", suffix=".pem", delete=False) as f:
        f.write("\n".join(p for _, p, _ in chosen)); tmp = f.name
    if not no_net:
        for h in HOSTS:
            if not chain_ok(h, tmp):
                os.unlink(tmp); sys.exit("bundle cannot verify %s - not writing header" % h)
            print("live chain OK: %s anchors to the bundle" % h)
    os.unlink(tmp)

    hdr = ["// GENERATED by tools/fetch_roots.py - DO NOT EDIT BY HAND.",
           "// Regenerate: python3 tools/fetch_roots.py   (procedure: docs/CERTS.md)",
           "// Roots only; intermediates arrive with the live chain.",
           "#pragma once", ""]
    for cn, _, why in chosen:
        hdr.append("// root: %-32s %s" % (cn, why))
    hdr += ['static const char CA_BUNDLE[] PROGMEM = R"PEMBUNDLE(', ""]
    for _, pem, _ in chosen:
        hdr.append(pem)
    hdr.append(')PEMBUNDLE";')
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(hdr) + "\n")
    print("wrote %s (%d bytes, %d roots)" % (OUT, os.path.getsize(OUT), len(chosen)))

main()
