#!/usr/bin/env python3
"""Generate TFT_eSPI smooth (anti-aliased) fonts as C PROGMEM arrays.

Rasterizes a TTF with PIL/FreeType and emits byte arrays in the "vlw" format
parsed by TFT_eSPI Extensions/Smooth_font.cpp:

  header  : 6 x int32 BE -> gCount, version(11), sizeInPoints, 0, ascent, descent
  glyphs  : gCount x 7 x int32 BE -> unicode, h, w, xAdvance, dY, dX, pad
  bitmaps : packed 8-bit alpha, glyph order, offsets = 24 + 28*gCount + sum(w*h)
  trailer : nameLen, name, psNameLen, psName, aaFlag(1)

Usage:
  gen_smooth_font.py <font.ttf> <out.h> <size> [<size> ...]
  size spec: <px>            full ASCII + ° · — …
             <px>:digits     clock subset "0123456789:-" with tabular advances
             <px>:numeric    same subset, proportional advances (like the full font)
"""
import struct
import sys

from PIL import Image, ImageFont

ASCII_FULL = [c for c in range(0x20, 0x7F)] + [0xB0, 0xB7, 0x2014, 0x2026]  # printable + ° · — …
DIGITS = [ord(c) for c in "0123456789:-"]  # "-" for the "--:--:--" placeholder
NAME = "Inter SemiBold"


def mask_bytes(mask):
    try:
        return mask.tobytes()
    except AttributeError:
        return bytes(mask)


def build_glyphs(font, codes, tabular):
    glyphs = []
    for code in sorted(set(codes)):
        ch = chr(code)
        bbox = font.getbbox(ch)  # anchor "la": y measured from ascender line
        mask = font.getmask(ch, mode="L")
        bw, bh = bbox[2] - bbox[0], bbox[3] - bbox[1]
        mw, mh = mask.size
        if (bw, bh) != (mw, mh):
            # Pillow can return a slightly different box; trust the mask
            bw, bh = mw, mh
        adv = int(round(font.getlength(ch)))
        glyphs.append({
            "code": code,
            "w": bw,
            "h": bh,
            "adv": adv,
            "dX": bbox[0],
            "dY": None,  # filled after ascent is known
            "bmp": mask_bytes(mask) if bw and bh else b"",
        })

    if tabular:
        cell = max(g["adv"] for g in glyphs)
        for g in glyphs:
            if g["code"] in DIGITS:
                # center narrower digits inside the fixed cell
                g["dX"] += (cell - g["adv"]) // 2
                g["adv"] = cell
    return glyphs


def assemble(glyphs, size, ascent, descent, font_name):
    out = bytearray()
    out += struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    for g in glyphs:
        out += struct.pack(">7i", g["code"], g["h"], g["w"], g["adv"],
                           g["dY"], g["dX"], 0)
    for g in glyphs:
        out += g["bmp"]
    nb = font_name.encode("ascii")
    out += bytes([len(nb)]) + nb + bytes([len(nb)]) + nb + b"\x01"
    return bytes(out)


def parse_back(data):
    """Read the array back the same way loadMetrics does (sanity check)."""
    (count, ver, pts, zero, asc, desc) = struct.unpack_from(">6i", data, 0)
    ptr = 24 + count * 28
    glyphs = []
    for i in range(count):
        code, h, w, adv, dy, dx, pad = struct.unpack_from(">7i", data, 24 + 28 * i)
        glyphs.append((code, h, w, adv, dy, dx, ptr))
        ptr += w * h
    return count, asc, desc, glyphs


def emit_c(name, data, out):
    out.write("// Auto-generated by tools/gen_smooth_font.py - do not edit.\n")
    out.write("static const uint8_t %s[] PROGMEM = {\n" % name)
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        out.write("  " + ",".join(str(b) for b in chunk) + ",\n")
    out.write("};\n\n")


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    ttf, out_h = sys.argv[1], sys.argv[2]
    specs = sys.argv[3:]

    with open(out_h, "w") as out:
        out.write("// Smooth (anti-aliased) fonts for TFT_eSPI (vlw format).\n")
        out.write("// Generated from %s - do not edit by hand.\n\n"
                  % ttf.rsplit("/", 1)[-1])
        for spec in specs:
            tabular = spec.endswith(":digits")
            numeric = spec.endswith(":numeric")
            size = int(spec.split(":")[0])
            codes = DIGITS if (tabular or numeric) else ASCII_FULL
            font = ImageFont.truetype(ttf, size)
            ascent, descent = font.getmetrics()
            glyphs = build_glyphs(font, codes, tabular)
            for g in glyphs:
                g["dY"] = ascent - font.getbbox(chr(g["code"]))[1]
            data = assemble(glyphs, size, ascent, descent, NAME)

            count, a, d, check = parse_back(data)
            assert count == len(glyphs)
            assert check[-1][6] + check[-1][1] * check[-1][2] <= len(data)
            for g, c in zip(glyphs, check):
                assert g["code"] == c[0] and g["w"] == c[2] and g["h"] == c[1]
                assert 0 <= g["adv"] <= 255 and -128 <= g["dX"] <= 127

            sym = "Font_%d%s" % (size, "_digits" if tabular else ("_numeric" if numeric else ""))
            emit_c(sym, data, out)
            px = sum(g["w"] * g["h"] for g in glyphs)
            print("%-14s %3d glyphs, ascent %d, descent %d, "
                  "%d B total (%d B bitmaps)"
                  % (sym, count, a, d, len(data), px))


if __name__ == "__main__":
    main()
